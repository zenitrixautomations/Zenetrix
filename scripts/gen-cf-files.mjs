// Generates public/_headers and public/_redirects for Cloudflare Pages (static export ignores next.config headers()/redirects()).
// Runs automatically before `next build`. Source of truth for legacy redirects: data/redirects.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://challenges.cloudflare.com https://www.clarity.ms https://*.clarity.ms",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https://res.cloudinary.com https://www.google-analytics.com https://www.googletagmanager.com https://*.clarity.ms https://c.bing.com",
  "font-src 'self' data:",
  "connect-src 'self' https://www.google-analytics.com https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com https://challenges.cloudflare.com https://*.clarity.ms https://c.bing.com",
  "media-src 'self' data: blob: https://res.cloudinary.com",
  "frame-src https://challenges.cloudflare.com",
  "object-src 'none'", "worker-src 'self' blob:", "manifest-src 'self'",
  "frame-ancestors 'none'", "base-uri 'self'", "form-action 'self' https://wa.me",
  "upgrade-insecure-requests",
].join('; ')

const headers = `# Generated by scripts/gen-cf-files.mjs. Do not edit by hand.
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  Cross-Origin-Opener-Policy: same-origin-allow-popups
  X-Permitted-Cross-Domain-Policies: none
  X-DNS-Prefetch-Control: on
  Content-Security-Policy: ${csp}

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/api/*
  Cache-Control: no-store
`
if (headers.split('\n').some(l => l.length > 2000)) throw new Error('A _headers line exceeds Cloudflare 2000 char limit')

const legacy = JSON.parse(readFileSync(new URL('../data/redirects.json', import.meta.url), 'utf8'))
const norm = p => (p.length > 1 && p.endsWith('/') ? p.slice(0, -1) : p)
const lines = new Set()
for (const r of legacy) { lines.add(`${r.from} ${r.to} 301`); if (r.from.length > 1 && r.from.endsWith('/')) lines.add(`${norm(r.from)} ${r.to} 301`) }
const redirects = `# Generated by scripts/gen-cf-files.mjs from data/redirects.json (www -> non-www is a Cloudflare Redirect Rule, see DEPLOY.md)\n${[...lines].join('\n')}\n`

mkdirSync(new URL('../public/', import.meta.url), { recursive: true })
writeFileSync(new URL('../public/_headers', import.meta.url), headers)
writeFileSync(new URL('../public/_redirects', import.meta.url), redirects)
console.log(`[cf] wrote public/_headers and public/_redirects (${lines.size} redirects)`)
